#!/usr/bin/env node
// Regenerates src/lib/api-types.ts from the backend's OpenAPI spec (DESIGN.md section 7: "OpenAPI
// is the contract... generate types from it... regenerate as a checked-in build step so the diff
// is visible in review").
//
// The spec is only served in Development (see Program.cs), so this briefly starts the API with
// a throwaway config, fetches /swagger/v1/swagger.json, then stops it. Run manually after an API
// change that affects a DTO shape: `pnpm run generate-api-types`.

import { spawn } from "node:child_process";
import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const clientDir = fileURLToPath(new URL("..", import.meta.url));
const apiProjectDir = join(clientDir, "..", "AudiobookManager", "AudiobookManager.Api");
const outFile = join(clientDir, "src", "lib", "api-types.ts");
const port = 5299;
const specUrl = `http://localhost:${port}/swagger/v1/swagger.json`;

const scratch = mkdtempSync(join(tmpdir(), "abm-openapi-"));
mkdirSync(join(scratch, "import"), { recursive: true });
mkdirSync(join(scratch, "library"), { recursive: true });
mkdirSync(join(scratch, "config"), { recursive: true });

const child = spawn("dotnet", ["run", "--urls", `http://localhost:${port}`], {
  cwd: apiProjectDir,
  env: {
    ...process.env,
    ASPNETCORE_ENVIRONMENT: "Development",
    AudiobookImportPath: join(scratch, "import"),
    AudiobookLibraryPath: join(scratch, "library"),
    DbLocation: join(scratch, "config", "audiobookmanager.db"),
  },
  stdio: "pipe",
});

let stderr = "";
child.stderr?.on("data", (d) => (stderr += d.toString()));

function stop() {
  child.kill("SIGTERM");
  rmSync(scratch, { recursive: true, force: true });
}

async function waitForSpec(timeoutMs = 60_000) {
  const start = Date.now();
  while (Date.now() - start < timeoutMs) {
    try {
      const res = await fetch(specUrl);
      if (res.ok) return await res.text();
    } catch {
      // API not up yet.
    }
    if (child.exitCode !== null) {
      throw new Error(`dotnet run exited early (code ${child.exitCode}).\n${stderr}`);
    }
    await new Promise((r) => setTimeout(r, 1000));
  }
  throw new Error(`Timed out waiting for ${specUrl}`);
}

try {
  const specJson = await waitForSpec();
  const specFile = join(scratch, "swagger.json");
  writeFileSync(specFile, specJson);

  const { default: openapiTS, astToString } = await import("openapi-typescript");
  const ast = await openapiTS(new URL(`file://${specFile}`), {});
  const header = [
    "// Generated by openapi-typescript from the backend's OpenAPI spec — do not hand-edit.",
    "// Regenerate with `pnpm run generate-api-types` after a DTO shape changes.",
    "",
  ].join("\n");
  writeFileSync(outFile, header + astToString(ast));
  console.log(`Wrote ${outFile}`);
} finally {
  stop();
}
